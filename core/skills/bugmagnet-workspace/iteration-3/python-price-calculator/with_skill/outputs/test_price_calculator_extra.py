class TestCalculateDiscountBoundaries:
    def test_zero_discount_returns_original_price(self):
        assert calculate_discount(100.0, 0) == 100.0

    def test_100_percent_discount_returns_zero(self):
        assert calculate_discount(100.0, 100) == 0.0

    def test_zero_price_always_returns_zero(self):
        assert calculate_discount(0.0, 50) == 0.0

    def test_fractional_discount_rounds_to_two_decimal_places(self):
        # 10.00 - (10.00 * 33 / 100) = 10.00 - 3.30 = 6.70
        assert calculate_discount(10.0, 33) == 6.70

    def test_small_price_large_discount(self):
        # 0.01 with 50% → 0.005 rounds to 0.01 (half-up rounding)
        result = calculate_discount(0.01, 50)
        assert result == round(0.01 - (0.01 * 50 / 100), 2)

    def test_negative_discount_increases_price(self):
        # Negative discount_percent is not guarded — it raises the price.
        # Documenting current (permissive) behaviour.
        result = calculate_discount(100.0, -10)
        assert result == 110.0

    def test_discount_over_100_produces_negative_price(self):
        # No guard against discount > 100; result goes below zero.
        result = calculate_discount(100.0, 150)
        assert result == -50.0

    def test_negative_price_with_positive_discount(self):
        # Discounting a negative price makes it more negative — no guard.
        result = calculate_discount(-100.0, 10)
        assert result == -90.0


